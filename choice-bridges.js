function apply(){const story=document.getElementById('sceneText');if(!story)return;story.querySelectorAll('.choice-result').forEach(n=>n.remove());let p=null;try{p=JSON.parse(sessionStorage.getItem(KEY)||'null')}catch(_){p=null}if(!p||!bridges[p.label]||Date.now()-p.time>5000)return;const el=document.createElement('p');el.className='choice-result';el.textContent=bridges[p.label];story.prepend(el);sessionStorage.removeItem(KEY)}
